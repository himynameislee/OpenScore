"""Generate the reference pages in docs/ from the program itself, so they can't drift.

    python3 -m openscore.docgen          # rewrite docs/command-reference.md and docs/check-catalog.md
    python3 -m openscore.docgen --check  # exit 1 if either file is out of date (CI runs this as a test)

Only help text and the knowledge base are rendered. Argument defaults are never read, because some
of them come from environment variables (API keys).
"""
from __future__ import annotations

import argparse
import os
import re
import sys

from . import kb

HEADER = "<!-- Generated by `python3 -m openscore.docgen`. Don't edit by hand. -->\n\n"
SEV_ORDER = {"critical": 0, "high": 1, "medium": 2, "low": 3, "info": 4, "pass": 5}


def _cell(text: str) -> str:
    """One line of Markdown: collapse whitespace, escape table pipes, and escape "<" outside code
    spans so placeholders like <port> aren't swallowed as HTML tags."""
    text = " ".join((text or "").split()).replace("|", "\\|")
    parts = re.split(r"(`[^`]*`)", text)
    return "".join(p if p.startswith("`") else p.replace("<", "&lt;") for p in parts)


def _option_names(action: argparse.Action) -> str:
    if not action.option_strings:
        return f"`{action.metavar or action.dest}`"
    names = ", ".join(f"`{s}`" for s in action.option_strings)
    if action.nargs == 0:
        return names
    meta = action.metavar or action.dest.upper()
    if action.nargs in ("*",):
        return f"{names} `{meta} ...`"
    return f"{names} `{meta}`"


def command_reference() -> str:
    from .cli import QUICK_START, _parser
    p = _parser()
    out = [HEADER, "# Command reference\n\n",
           "Every option `openscore` accepts, generated from its own `-h`. Run `openscore -h` for the same "
           "list in a terminal.\n\n",
           "```\n", p.usage.replace("%(prog)s", "openscore"), "\n```\n\n",
           _cell(p.description), "\n"]
    for group in p._action_groups:
        actions = [a for a in group._group_actions if a.help is not argparse.SUPPRESS]
        if not actions:
            continue
        title = group.title
        if title in ("positional arguments", "options", "optional arguments"):
            title = "general" if title != "positional arguments" else "domain"
        out += [f"\n## {title[0].upper()}{title[1:]}\n\n", "| Option | What it does |\n|---|---|\n"]
        for a in actions:
            text = a.help or ""
            if "%(" in text:
                text = text % {"prog": "openscore"}
            if isinstance(a, argparse._HelpAction):
                text = "Show the help and exit"
            elif isinstance(a, argparse._VersionAction):
                text = "Print the version and exit"
            out.append(f"| {_option_names(a)} | {_cell(text)} |\n")
    out += ["\n## Examples and output (from `openscore -h`)\n\n```\n", QUICK_START.rstrip(), "\n```\n"]
    return "".join(out)


def check_catalog() -> str:
    out = [HEADER, "# Check catalog\n\n",
           f"All {len(kb.CHECKS)} checks OpenScore can report, grouped by factor, generated from the "
           "knowledge base (`openscore/kb.py`). The severity is the default; a few checks adjust it "
           "from what they find (for example, certificate expiry gets more severe as the date gets "
           "closer). Findings matched only on a version banner are reported as *tentative*.\n\n",
           "In the verify commands, `{asset}` is the host or IP, `{domain}` the domain you scanned and "
           "`{url}` the URL in the evidence; the report fills them in.\n\n",
           "Third-party results (nuclei templates, testssl.sh rows) use the generic `nuclei_finding` "
           "and `tls_testssl` entries, with the tool's own title.\n\n"]
    out.append("| Factor | Weight | Checks |\n|---|---|---|\n")
    for fid, f in kb.FACTORS.items():
        n = sum(1 for c in kb.CHECKS.values() if c["factor"] == fid)
        out.append(f"| [{f['name']}](#{fid}) | {f['weight']} | {n} |\n")
    for fid, f in kb.FACTORS.items():
        checks = sorted(((cid, c) for cid, c in kb.CHECKS.items() if c["factor"] == fid),
                        key=lambda x: (SEV_ORDER.get(x[1]["severity"], 9), x[0]))
        out.append(f'\n<a id="{fid}"></a>\n\n## {f["name"]}\n\n{_cell(f["desc"])}\n')
        for cid, c in checks:
            out.append(f"\n### {c['title']}\n\n")
            sev = "passed check (no deduction)" if c["severity"] == "pass" else f"default severity **{c['severity']}**"
            out.append(f"`{cid}` · {sev}\n\n")
            if c.get("description"):
                out.append(f"**Why it matters:** {_cell(c['description'])}\n\n")
            verify = kb.VERIFY.get(cid)
            if verify:
                out.append(f"**How to verify:** {_cell(verify)}\n\n")
            if c.get("remediation"):
                out.append(f"**How to fix:** {_cell(c['remediation'])}\n\n")
            if c.get("refs"):
                out.append("**References:** " + ", ".join(f"<{r}>" for r in c["refs"]) + "\n")
    return "".join(out).rstrip() + "\n"


PAGES = {"command-reference.md": command_reference, "check-catalog.md": check_catalog}


def docs_dir() -> str:
    return os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "docs")


def stale(directory: str | None = None) -> list[str]:
    d = directory or docs_dir()
    bad = []
    for name, fn in PAGES.items():
        path = os.path.join(d, name)
        try:
            with open(path, encoding="utf-8") as fh:
                current = fh.read()
        except OSError:
            current = None
        if current != fn():
            bad.append(name)
    return bad


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python3 -m openscore.docgen")
    ap.add_argument("--check", action="store_true", help="Only report out-of-date pages (exit 1)")
    args = ap.parse_args(argv)
    if args.check:
        bad = stale()
        for name in bad:
            print(f"docs/{name} is out of date: run python3 -m openscore.docgen")
        return 1 if bad else 0
    for name, fn in PAGES.items():
        with open(os.path.join(docs_dir(), name), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(fn())
        print(f"wrote docs/{name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
